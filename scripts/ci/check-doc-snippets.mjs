/**
 * Typecheck every TypeScript snippet in the guides, against the library's real types.
 *
 * The reason this exists: two snippets in `docs/vacuums.md` did not compile — one named a setter that
 * does not exist (`setLevel` for `setSuctionLevel`), the other read a method as a property (`scenes`
 * rather than `scenes()`) — and a READER found them, not CI. Nothing in the repo compiled the guides,
 * so a rename in `src/` could silently make the documentation wrong, which is the failure mode a guide
 * has: it is believed.
 *
 *   node scripts/ci/check-doc-snippets.mjs          check (CI)
 *   node scripts/ci/check-doc-snippets.mjs --keep   leave the generated files for inspection
 *
 * ## How a fragment is made compilable
 *
 * A guide snippet is a FRAGMENT: it says `await clean?.startScene?.(first.id)` without ever declaring
 * `clean`, because the surrounding prose declared it. Two moves make that typecheckable without
 * rewriting a single snippet:
 *
 *  1. The shared vocabulary (`dev`, `eufy`, `station`, …) is declared ambiently in a prelude, so a
 *     snippet may use any of it without introducing it.
 *  2. The snippet's own body is wrapped in a function. That is what makes the prelude safe: a snippet
 *     that declares its own `const dev = await eufy.getDevice(sn)` SHADOWS the ambient one, which is
 *     legal, where a prelude in the same scope would collide. It also gives `await` somewhere to live.
 *
 * Snippets are not executed — `--noEmit` only. A guide is checked for whether it TYPES, which is the
 * half that rots under a rename; whether it runs needs a device and belongs in `examples/`.
 *
 * ## When a snippet genuinely cannot compile
 *
 * Mark it in the markdown, immediately above the fence, with a reason:
 *
 *     <!-- typecheck: skip — pseudocode for the retry shape, not real API -->
 *
 * The reason is required: a bare skip is rejected, because the point of the marker is that someone
 * decided, not that a snippet was inconvenient. An HTML comment renders as nothing, so the guide is
 * unchanged for a reader.
 */

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const DOCS = join(ROOT, "docs");
const OUT = join(ROOT, "docs", ".snippets");
const keep = process.argv.includes("--keep");

/**
 * The names a guide may use without declaring them, and what each is.
 *
 * Ambient `declare const`, so nothing here is a value at runtime and nothing here can be wrong about
 * behaviour — only about TYPE, which is exactly what is being checked. Every entry is a name the prose
 * of some guide introduces; adding one is a claim that the guides really do use it that way, so keep it
 * to the shared vocabulary rather than smuggling a per-snippet fixture in here.
 */
const PRELUDE = `
// GENERATED by scripts/ci/check-doc-snippets.mjs — do not edit; not committed.
// A TYPE-ONLY namespace import, deliberately: it introduces exactly one name, so a snippet is free to
// \`import { EufyMega } from "@mega-yfue/eufy-sdk"\` without colliding with anything declared here.
// Naming the classes directly made every such snippet fail twice over — once as a duplicate identifier,
// once as "cannot be used as a value because it was imported using import type".
import type * as Sdk from "../../src/index.ts";

// The shared vocabulary of the guides: names the prose introduces and the snippets then use. Ambient,
// so none of this is a value at runtime and none of it can be wrong about behaviour — only about TYPE,
// which is the half a rename breaks. A snippet that declares its own \`const dev = …\` shadows these,
// because the snippet body lives inside a function.
//
// Each name's TYPE matters as much as its presence: \`cam\` is the camera capability surface
// (\`dev.camera?.()\`) and not a Device, and typing it as a Device made every \`cam.live()\` in the media
// guide look like a guide error when the guide was right.
declare const eufy: Sdk.EufyMega;
declare const dev: Sdk.Device;
declare const station: Sdk.Device;
declare const cam: NonNullable<ReturnType<NonNullable<Sdk.Device["camera"]>>>;
// The SMART light (\`dev.smartLight?.()\`), which is the only \`light\` the guides introduce by that name;
// a camera's floodlight is reached through \`cam\` and never bound to a bare \`light\`.
declare const light: NonNullable<ReturnType<NonNullable<Sdk.Device["smartLight"]>>>;
declare const ptz: NonNullable<ReturnType<NonNullable<Sdk.Device["ptz"]>>>;
declare const rtsp: NonNullable<ReturnType<NonNullable<Sdk.Device["rtsp"]>>>;
declare const manifest: Sdk.DeviceManifest;
declare const store: Sdk.SessionStore;
declare const sn: string;
declare const stationSn: string;
declare const email: string;
declare const password: string;
declare const country: string;
declare const countryCode: string;
declare const secret: string;

// Names a guide introduces for something OUTSIDE this library: the host's own logger, its prompt, its
// file system. Typed loosely on purpose — the claim a snippet makes about them is not this SDK's to
// check, and a precise type here would only invent an interface the reader does not have.
declare const myLog: Sdk.Logger;
declare const promptUser: (question: string) => Promise<string>;
declare const fs: typeof import("node:fs");
declare const kind: string;

// The live stream a snippet has already opened, and whatever the host is piping it into. \`sink\` is a
// Node writable in every guide that names one, so it is typed as one rather than as a hand-written pair
// of methods — the snippets use \`once\`, and inventing a narrower interface here only breaks them.
declare const stream: Awaited<ReturnType<NonNullable<typeof cam.live>>>;
declare const sink: import("node:stream").Writable;
`.trimStart();

/** Lines the prelude occupies, so an error in a generated file maps back to a markdown line. */
const PRELUDE_LINES = PRELUDE.split("\n").length;

/**
 * Names the guides use as VALUES that a snippet may equally well import for itself.
 *
 * These cannot go in the prelude. `declare const EufyMega` at module scope collides with a snippet's own
 * `import { EufyMega } from "@mega-yfue/eufy-sdk"` — both bind the name in the same scope, and TypeScript
 * calls that a duplicate identifier. So each is emitted INSIDE the wrapper function instead, and only
 * for a snippet that did not import it: an import wins by being in the outer scope, and a snippet that
 * imports the wrong name still fails, which is the check worth keeping.
 */
const AMBIENT_VALUES = {
  EufyMega: "const EufyMega = null as unknown as typeof Sdk.EufyMega;",
  ConsoleLogger: "const ConsoleLogger = null as unknown as typeof Sdk.ConsoleLogger;",
  MemorySessionStore: "const MemorySessionStore = null as unknown as typeof Sdk.MemorySessionStore;",
  FileSessionStore: "const FileSessionStore = null as unknown as typeof Sdk.FileSessionStore;",
  listLightEffects: "const listLightEffects = null as unknown as typeof Sdk.listLightEffects;",
};

/** The names a snippet's hoisted declarations already bind, so they are not shadowed by the above. */
function importedNames(hoisted) {
  const names = new Set();
  for (const m of hoisted.matchAll(/\{([^}]*)\}/g)) {
    for (const part of m[1].split(",")) {
      const name = part
        .trim()
        .replace(/^type\s+/, "")
        .split(/\s+as\s+/)
        .pop()
        ?.trim();
      if (name) names.add(name);
    }
  }
  // A default or namespace import: `import X from …` / `import * as X from …`.
  for (const m of hoisted.matchAll(/import\s+(?:\*\s+as\s+)?([A-Za-z_$][\w$]*)\s*(?:,|from)/g)) names.add(m[1]);
  return names;
}

/**
 * The ellipsis a guide uses to elide a body, made compilable without changing what a reader sees.
 *
 * `eufy.on("motion", (e) => …)` is the clearest way to write "and here you do something with it", and
 * every reader understands it — but it is not TypeScript, and the interesting half of that line (the
 * event name, and the fields of `e`) is exactly what rots under a rename. Rewriting the guides to
 * `(e) => {}` to satisfy a checker would make them worse to read in order to make them checkable, so
 * the checker gives way instead: a bare `…` becomes an expression of type `never`, which is assignable
 * wherever a value is expected and never masks a type error of its own.
 *
 * Only OUTSIDE strings, template literals and comments — `description: "…"` is already valid and must
 * stay a string, and an ellipsis in prose inside a comment is not code at all. Hence a scan rather
 * than a replace: the state machine is small, and getting this wrong would either break valid snippets
 * or silently edit their meaning.
 */
function expandElisions(code) {
  let out = "";
  let quote;
  let comment;
  for (let i = 0; i < code.length; i++) {
    const c = code[i];
    const next = code[i + 1];
    if (comment === "line") {
      if (c === "\n") comment = undefined;
      out += c;
      continue;
    }
    if (comment === "block") {
      if (c === "*" && next === "/") {
        comment = undefined;
        out += "*/";
        i += 1;
        continue;
      }
      out += c;
      continue;
    }
    if (quote) {
      // A backslash escapes the next character, so an escaped quote does not end the string.
      if (c === "\\") {
        out += c + (next ?? "");
        i += 1;
        continue;
      }
      if (c === quote) quote = undefined;
      out += c;
      continue;
    }
    if (c === "/" && next === "/") {
      comment = "line";
      out += "//";
      i += 1;
      continue;
    }
    if (c === "/" && next === "*") {
      comment = "block";
      out += "/*";
      i += 1;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") {
      quote = c;
      out += c;
      continue;
    }
    out += c === "\u2026" ? "(undefined as never)" : c;
  }
  return out;
}

/**
 * Split a snippet into the declarations that must sit at module scope and the rest of the body.
 *
 * The wrapper function is what lets a snippet's own `const` shadow the prelude — but an `import` is
 * illegal inside a function, and several guides consist of nothing else (`import { LIVE_TRACE_MESSAGE,
 * type LiveTrace } from "@mega-yfue/eufy-sdk"` is the whole snippet in the troubleshooting guide, and
 * it is a claim worth checking: it says those two names are exported from the package root).
 *
 * Only a line that STARTS a top-level `import`/`export` is hoisted, and its continuation lines with it,
 * so a multi-line import list survives. An `import()` expression is untouched — it is an expression and
 * belongs where it was written.
 */
function hoistDeclarations(body) {
  const hoisted = [];
  const rest = [];
  let carrying = false;
  for (const line of body.split("\n")) {
    const starts = /^\s*(?:import|export)\s+(?![(.])/.test(line);
    if (starts || carrying) {
      hoisted.push(line);
      // A declaration continues until its statement ends; `from "…";` or a bare `;` closes it, and a
      // single-line form closes immediately.
      carrying = !/;\s*$/.test(line) && !/^\s*export\s+(?:async\s+)?(?:function|class|const|let|var)\b/.test(line);
      continue;
    }
    rest.push(line);
  }
  return { hoisted: hoisted.join("\n"), body: rest.join("\n"), hoistedCount: hoisted.length };
}

/** Markdown files to scan, deepest-first so a nested guide is found too. */
function markdownFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...markdownFiles(path));
    else if (entry.name.endsWith(".md")) out.push(path);
  }
  return out;
}

/** `<!-- typecheck: skip — why -->`, which must carry a reason. */
const SKIP = /^<!--\s*typecheck:\s*skip\s*(?:[—-]\s*(?<reason>.+?))?\s*-->$/;

/**
 * Every ```ts block in one file: its body, the line its first code line sits on, and any skip marker.
 *
 * Hand-rolled rather than pulled from a markdown parser: the only structure needed is a fence, and a
 * dependency that understands the whole of CommonMark to find ``` is a poor trade in a CI script.
 */
function snippetsIn(markdown) {
  const lines = markdown.split("\n");
  const found = [];
  let skip;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    const marker = SKIP.exec(line);
    if (marker) {
      skip = { reason: marker.groups?.reason, line: i + 1 };
      continue;
    }
    if (line !== "```ts") {
      // A blank line between the marker and its fence is fine; anything else means the marker was
      // orphaned, which is worth reporting rather than silently applying to a later snippet.
      if (line !== "" && skip) found.push({ orphanedSkip: skip });
      if (line !== "") skip = undefined;
      continue;
    }
    const start = i + 1;
    // Closed by TRIMMED comparison, because a fence inside a list item is indented and so is its
    // closer. Matching the bare string meant an indented block was never closed: it swallowed the rest
    // of the file — prose, further fences and all — and reported the markdown as broken TypeScript.
    let close = lines.length;
    for (let j = start; j < lines.length; j++) {
      if (lines[j].trim() === "```") {
        close = j;
        break;
      }
    }
    found.push({ body: lines.slice(start, close).join("\n"), firstLine: start + 1, skip });
    skip = undefined;
    i = close;
  }
  return found;
}

const problems = [];
const generated = [];

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

for (const file of markdownFiles(DOCS)) {
  const rel = relative(ROOT, file);
  const snippets = snippetsIn(readFileSync(file, "utf8"));
  let n = 0;
  for (const snippet of snippets) {
    if (snippet.orphanedSkip) {
      problems.push(`${rel}:${snippet.orphanedSkip.line} typecheck:skip marker is not above a \`\`\`ts fence`);
      continue;
    }
    if (snippet.skip) {
      if (!snippet.skip.reason) {
        problems.push(`${rel}:${snippet.skip.line} typecheck:skip needs a reason — \`<!-- typecheck: skip — why -->\``);
      }
      continue;
    }
    n += 1;
    const name = `${rel.replace(/[/\\]/g, "__").replace(/\.md$/, "")}-${n}.ts`;
    // The body goes inside a function so its own `const`s shadow the prelude and `await` is legal.
    const { hoisted, body, hoistedCount } = hoistDeclarations(expandElisions(snippet.body));
    const bound = importedNames(hoisted);
    const shadow = Object.entries(AMBIENT_VALUES)
      .filter(([n]) => !bound.has(n))
      .map(([, decl]) => decl)
      .join("\n");
    // Hoisted lines keep their own order but move above the wrapper, so a line number inside the body
    // is offset by however many left it. The shadow block sits on ONE line for the same reason: a fixed,
    // known height keeps the markdown line mapping arithmetic honest.
    const shadowLine = shadow.split("\n").join(" ");
    writeFileSync(
      join(OUT, name),
      `${PRELUDE}${hoisted}\nexport async function snippet(): Promise<void> {\n${shadowLine}\n${body}\n}\n`,
    );
    generated.push({ name, rel, firstLine: snippet.firstLine, hoistedCount });
  }
}

writeFileSync(
  join(OUT, "tsconfig.json"),
  `${JSON.stringify(
    {
      compilerOptions: {
        target: "ES2024",
        lib: ["ES2024", "DOM"],
        module: "NodeNext",
        moduleResolution: "NodeNext",
        strict: true,
        noEmit: true,
        allowImportingTsExtensions: true,
        esModuleInterop: true,
        skipLibCheck: true,
        types: ["node"],
        // A guide shows the interesting call, not a use for its result: `const scenes = clean?.scenes?.()`
        // with nothing reading `scenes` is correct prose and would be noise here.
        noUnusedLocals: false,
        noUnusedParameters: false,
        // The guides import the package by its published NAME, which is what a reader will type. Mapped
        // to the source so a snippet is checked against what this commit actually exports rather than
        // against whatever version happens to be installed in node_modules.
        // No `baseUrl` — TypeScript 7 removed it, and `paths` is resolved relative to this tsconfig.
        paths: { "@mega-yfue/eufy-sdk": ["../../src/index.ts"] },
      },
      include: ["*.ts"],
    },
    null,
    2,
  )}\n`,
);

if (generated.length) {
  try {
    execFileSync("npx", ["tsc", "-p", join(OUT, "tsconfig.json")], { cwd: ROOT, stdio: "pipe" });
  } catch (err) {
    const output = `${err.stdout ?? ""}${err.stderr ?? ""}`;
    for (const line of output.split("\n")) {
      // `name.ts(LINE,COL): error TSxxxx: message` → the markdown line that produced it.
      const m = /^(?<name>[^(]+)\((?<line>\d+),(?<col>\d+)\):\s*(?<rest>.*)$/.exec(line.trim());
      if (!m) {
        if (line.trim()) problems.push(line.trimEnd());
        continue;
      }
      const source = generated.find((g) => g.name === m.groups.name.split(/[/\\]/).pop());
      if (!source) {
        problems.push(line.trimEnd());
        continue;
      }
      // A generated line sits after: the prelude, the hoisted declarations (which came from the body and
      // so are counted back), the shadow block, and the wrapper's own opening line.
      // prelude + the hoisted lines + the wrapper's opening line + the one-line shadow block.
      const preamble = PRELUDE_LINES + source.hoistedCount + 2;
      const offset = Number(m.groups.line) - preamble;
      problems.push(
        `${source.rel}:${source.firstLine + source.hoistedCount + offset}:${m.groups.col} ${m.groups.rest}`,
      );
    }
  }
}

if (!keep) rmSync(OUT, { recursive: true, force: true });

if (problems.length) {
  console.error(`::error::${problems.length} problem(s) in the guides' TypeScript snippets\n`);
  for (const p of problems) console.error(`  ${p}`);
  console.error(
    "\nA guide snippet is typechecked against the real library types. Fix the snippet, or — if it" +
      " genuinely cannot compile — put `<!-- typecheck: skip — reason -->` immediately above its fence.",
  );
  process.exit(1);
}

console.log(`doc snippets typecheck (${generated.length} checked)`);
